const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = vm.createContext({});
for (const file of ['site-config.js','products.js','catalog.js']) vm.runInContext(fs.readFileSync(path.join(root,'public',file),'utf8'),context);
const { product, catalog } = vm.runInContext('({product:products[0],catalog:Catalog})',context);
const first = {src:'/assets/products/test/first.jpg',alt:'Kelímek "A" & etiketa',caption:'Pohled <zepředu>'};
const second = {src:'/assets/products/test/second.jpg',thumbnail:'/assets/products/test/second-small.jpg',alt:'Detail konzistence'};
assert.ok(catalog.gallery({...product,photos:[]}).includes('/assets/design/levandulova-mast.webp'));
assert.ok(!catalog.gallery({...product,photos:[]}).includes('data-gallery'));
const single = catalog.gallery({...product,photos:[first]});
assert.ok(single.includes('Kelímek &quot;A&quot; &amp; etiketa'));
assert.ok(single.includes('Pohled &lt;zepředu&gt;'));
assert.ok(!single.includes('data-gallery-step'));
const multiple = catalog.gallery({...product,photos:[first,second]});
assert.equal((multiple.match(/data-gallery-index=/g) || []).length,2);
assert.ok(multiple.includes('Fotografie 1 z 2'));
assert.ok(multiple.includes('<noscript>'));
assert.ok(multiple.includes('src="/assets/products/test/second-small.jpg"'));
const card = catalog.card({...product,photos:[second,first]});
assert.ok(card.includes('src="/assets/products/test/second-small.jpg"'));
assert.ok(!card.includes('/assets/design/'));
console.log('OK: galerie 0/1/více snímků, pořadí, titulní náhled, přístupné popisy a escapování HTML.');
